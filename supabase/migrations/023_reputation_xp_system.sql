-- FULLSEND V17 — Sistema profissional de reputação e XP
-- ROOKIE → STREET → GEARHEAD → BUILDER → PRO BUILDER → ELITE → LEGEND

alter table public.profiles
  add column if not exists xp_points integer not null default 0,
  add column if not exists reputation_level text not null default 'ROOKIE';

do $$ begin
  alter table public.profiles add constraint profiles_xp_nonnegative check (xp_points >= 0);
exception when duplicate_object then null; end $$;

do $$ begin
  alter table public.profiles add constraint profiles_reputation_level_check
    check (reputation_level in ('ROOKIE','STREET','GEARHEAD','BUILDER','PRO BUILDER','ELITE','LEGEND'));
exception when duplicate_object then null; end $$;


-- Usuários comuns podem editar somente dados de perfil. XP, nível, função e selo
-- ficam protegidos no banco e só podem ser alterados pelo backend/service role.
revoke update on public.profiles from authenticated;
grant update(name,city,state,whatsapp,avatar_url,bio,instagram,updated_at) on public.profiles to authenticated;

create index if not exists profiles_xp_points_idx on public.profiles(xp_points desc);
create index if not exists profiles_reputation_level_idx on public.profiles(reputation_level);

create table if not exists public.xp_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  action_key text not null,
  points integer not null,
  source_type text not null default 'system',
  source_id text not null default 'general',
  note text,
  created_at timestamptz not null default now(),
  unique(user_id,action_key,source_type,source_id)
);

create index if not exists xp_ledger_user_created_idx on public.xp_ledger(user_id,created_at desc);
create index if not exists xp_ledger_action_date_idx on public.xp_ledger(action_key,created_at desc);

alter table public.xp_ledger enable row level security;
drop policy if exists "xp_ledger_self_read" on public.xp_ledger;
create policy "xp_ledger_self_read" on public.xp_ledger for select to authenticated using(user_id=auth.uid());
drop policy if exists "xp_ledger_admin_read" on public.xp_ledger;
create policy "xp_ledger_admin_read" on public.xp_ledger for select to authenticated using(
  exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin')
);
grant select on public.xp_ledger to authenticated;
grant all privileges on public.xp_ledger to service_role;
grant usage,select on sequence public.xp_ledger_id_seq to service_role;

create or replace function public.fullsend_level_for_xp(p_xp integer)
returns text language sql immutable as $$
  select case
    when greatest(coalesce(p_xp,0),0) >= 12000 then 'LEGEND'
    when greatest(coalesce(p_xp,0),0) >= 6000 then 'ELITE'
    when greatest(coalesce(p_xp,0),0) >= 3000 then 'PRO BUILDER'
    when greatest(coalesce(p_xp,0),0) >= 1500 then 'BUILDER'
    when greatest(coalesce(p_xp,0),0) >= 750 then 'GEARHEAD'
    when greatest(coalesce(p_xp,0),0) >= 250 then 'STREET'
    else 'ROOKIE'
  end;
$$;

create or replace function public.award_xp(
  p_user uuid,
  p_action text,
  p_points integer,
  p_source_type text default 'system',
  p_source_id text default 'general',
  p_daily_cap integer default null,
  p_note text default null
)
returns integer
language plpgsql
security definer
set search_path=public
as $$
declare
  v_today integer:=0;
  v_award integer:=greatest(coalesce(p_points,0),0);
  v_inserted bigint;
begin
  if p_user is null or v_award<=0 then return 0; end if;
  if not exists(select 1 from public.profiles where id=p_user) then return 0; end if;

  if exists(
    select 1 from public.xp_ledger
    where user_id=p_user and action_key=p_action and source_type=coalesce(nullif(p_source_type,''),'system') and source_id=coalesce(nullif(p_source_id,''),'general')
  ) then return 0; end if;

  if p_daily_cap is not null then
    select coalesce(sum(greatest(points,0)),0)::integer into v_today
    from public.xp_ledger
    where user_id=p_user and action_key=p_action and created_at>=date_trunc('day',now());
    v_award:=least(v_award,greatest(p_daily_cap-v_today,0));
    if v_award<=0 then return 0; end if;
  end if;

  insert into public.xp_ledger(user_id,action_key,points,source_type,source_id,note)
  values(p_user,p_action,v_award,coalesce(nullif(p_source_type,''),'system'),coalesce(nullif(p_source_id,''),'general'),p_note)
  on conflict(user_id,action_key,source_type,source_id) do nothing
  returning id into v_inserted;

  if v_inserted is null then return 0; end if;

  update public.profiles
  set xp_points=greatest(coalesce(xp_points,0)+v_award,0),
      reputation_level=public.fullsend_level_for_xp(greatest(coalesce(xp_points,0)+v_award,0)),
      updated_at=now()
  where id=p_user;

  return v_award;
end;
$$;

revoke all on function public.award_xp(uuid,text,integer,text,text,integer,text) from public,anon,authenticated;
grant execute on function public.award_xp(uuid,text,integer,text,text,integer,text) to service_role;

-- Publicação de anúncio FULLSEND: +40, apenas uma vez por anúncio.
create or replace function public.xp_on_listing_active() returns trigger
language plpgsql security definer set search_path=public as $$
begin
  if new.source='fullsend' and new.status='active' and new.user_id is not null then
    if tg_op='INSERT' then
      perform public.award_xp(new.user_id,'listing_published',40,'listing',new.id::text,null,'Anúncio publicado no FULLSEND');
    elsif tg_op='UPDATE' and old.status is distinct from new.status then
      perform public.award_xp(new.user_id,'listing_published',40,'listing',new.id::text,null,'Anúncio publicado no FULLSEND');
    end if;
  end if;
  return new;
end;$$;
drop trigger if exists trg_xp_listing_active on public.listings;
create trigger trg_xp_listing_active after insert or update of status on public.listings
for each row execute function public.xp_on_listing_active();

-- Evento criado por usuário e aprovado: +50 uma vez.
create or replace function public.xp_on_event_published() returns trigger
language plpgsql security definer set search_path=public as $$
begin
  if new.source='fullsend' and new.status='published' and new.created_by is not null then
    if tg_op='INSERT' then
      perform public.award_xp(new.created_by,'event_published',50,'event',new.id::text,null,'Evento aprovado no FULLSEND');
    elsif tg_op='UPDATE' and old.status is distinct from new.status then
      perform public.award_xp(new.created_by,'event_published',50,'event',new.id::text,null,'Evento aprovado no FULLSEND');
    end if;
  end if;
  return new;
end;$$;
drop trigger if exists trg_xp_event_published on public.events;
create trigger trg_xp_event_published after insert or update of status on public.events
for each row execute function public.xp_on_event_published();

-- Confirmar presença: +5, limite 25 XP/dia.
create or replace function public.xp_on_event_attendance() returns trigger
language plpgsql security definer set search_path=public as $$
begin
  perform public.award_xp(new.user_id,'event_attendance',5,'event_attendance',new.event_id::text||':'||new.user_id::text,25,'Presença confirmada em evento');
  return new;
end;$$;
drop trigger if exists trg_xp_event_attendance on public.event_attendees;
create trigger trg_xp_event_attendance after insert on public.event_attendees
for each row execute function public.xp_on_event_attendance();

-- Mensagem enviada: +2, limite 20 XP/dia.
create or replace function public.xp_on_message_sent() returns trigger
language plpgsql security definer set search_path=public as $$
begin
