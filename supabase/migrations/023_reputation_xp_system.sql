    perform public.award_xp(new.sender_id,'message_sent',2,'message',new.id::text,20,'Participação em conversa FULLSEND');
  end if;
  return new;
end;$$;
drop trigger if exists trg_xp_message_sent on public.messages;
create trigger trg_xp_message_sent after insert on public.messages
for each row execute function public.xp_on_message_sent();

-- Favorito recebido no anúncio: +3 para o anunciante, limite 30 XP/dia.
create or replace function public.xp_on_favorite_received() returns trigger
language plpgsql security definer set search_path=public as $$
declare v_owner uuid;
begin
  select user_id into v_owner from public.listings where id=new.listing_id and status='active';
  if v_owner is not null and v_owner<>new.user_id then
    perform public.award_xp(v_owner,'favorite_received',3,'favorite',new.listing_id::text||':'||new.user_id::text,30,'Favorito recebido em anúncio');
  end if;
  return new;
end;$$;
drop trigger if exists trg_xp_favorite_received on public.favorites;
create trigger trg_xp_favorite_received after insert on public.favorites
for each row execute function public.xp_on_favorite_received();

