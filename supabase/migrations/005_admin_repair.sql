-- Não falha se a policy já existir.
do $$ begin
  create policy "audit_admin_read" on public.audit_logs
    for select using (
      exists(
        select 1 from public.profiles p
        where p.id = auth.uid() and p.role = 'admin'
      )
    );
exception when duplicate_object then null;
end $$;

